import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const studies=JSON.parse(fs.readFileSync(path.join(root,'studies.json'),'utf8'));
const metrics=JSON.parse(fs.readFileSync(path.join(root,'qa/browser-metrics-390.json'),'utf8'));
const rgb=c=>[1,3,5].map(i=>parseInt(c.slice(i,i+2),16));
const lin=n=>{n/=255;return n<=.04045?n/12.92:((n+.055)/1.055)**2.4;};
const lum=c=>{const[r,g,b]=Array.isArray(c)?c:rgb(c);return .2126*lin(r)+.7152*lin(g)+.0722*lin(b);};
const ratio=(a,b)=>{const[hi,lo]=[lum(a),lum(b)].sort((a,b)=>b-a);return(hi+.05)/(lo+.05);};
const stops=[[0,.22],[.28,.03],[.38,.10],[.50,.80],[.62,.93],[.79,.98],[1,1]];
const alpha=y=>{for(let i=1;i<stops.length;i++){if(y<=stops[i][0]){const[a0,v0]=stops[i-1],[a1,v1]=stops[i];return v0+(v1-v0)*(y-a0)/(a1-a0);}}return 1;};
const composite=a=>[8,12,14].map(n=>255*(1-a)+n*a);
const results=studies.map(s=>{const m=metrics.find(m=>m.study===s.id&&m.kind==='event'),worst=composite(alpha(m.categoryY/m.hero));const checks={primary:ratio(s.text,s.panel),secondary:ratio(s.muted,s.panel),label:ratio(s.label,s.panel),date:ratio(s.accent,s.panel),footer:ratio(s.tertiary,s.bg),action:ratio('#211a13',s.accent),photoEyebrowWorstWhite:ratio(s.accent,worst),shortPhotoEyebrowWorstWhite:ratio(s.accent,composite(.86))};return{study:s.id,checks,pass:Object.values(checks).every(v=>v>=4.5)};});
fs.writeFileSync(path.join(root,'qa/contrast-results.json'),JSON.stringify(results,null,2));
console.log(results.map(s=>`${s.study}: ${s.pass?'PASS':'FAIL'}; lowest ${Math.min(...Object.values(s.checks)).toFixed(2)}:1`).join('\n'));
if(results.some(s=>!s.pass))process.exitCode=1;
