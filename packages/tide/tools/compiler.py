"""Shared theme compiler; used by the package and reference site."""
from pathlib import Path
import json
import re
from palette import resolve, checks, css

def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'Duplicate JSON key: {key}')
        result[key] = value
    return result


def load_themes(path):
    data = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique_object)
    if data.get('schemaVersion') != 1 or not data.get('themes'):
        raise ValueError('Expected schemaVersion 1 and a nonempty themes object.')
    resolved, audit = {}, {}
    for key, theme in data['themes'].items():
        if not re.fullmatch('[a-z][a-z0-9-]*', key):
            raise ValueError(f'Invalid theme identifier: {key}')
        if set(theme) - {'name','description','light','dark'}:
            raise ValueError(f'Unknown theme properties in {key}; geometry cannot be themed.')
        resolved[key], audit[key] = {}, {}
        for mode in ('light', 'dark'):
            if mode not in theme:
                raise ValueError(f'{key} must include {mode}.')
            if set(theme[mode]) - {'canvas', 'accent', 'overrides', 'texture'}:
                raise ValueError(f'Unknown palette input in {key}/{mode}.')
            allowed_roles = {'surface','raised','field','text-primary','text-secondary','text-muted','text-label','on-accent','border-subtle','border-strong','border-control','selected-surface','selected-text','selected-border'} | {f'status-{s}-{p}' for s in ('success','warning','danger') for p in ('text','surface','border')}
            if set(theme[mode].get('overrides', {})) - allowed_roles:
                raise ValueError(f'Unknown semantic override in {key}/{mode}.')
            if not 0 <= theme[mode].get('texture', .2) <= 1:
                raise ValueError('Texture opacity must be in the range 0..1.')
            resolved[key][mode] = resolve(theme[mode])
        # Photography is the theme's dark reading context in both page modes.
        photo_roles=[r for r in resolved[key]['dark'] if r.startswith('photo-') or r=='on-photo-accent']
        for mode in ('light','dark'):
            for role in photo_roles:
                resolved[key][mode][role]=resolved[key]['dark'][role]
            colors=resolved[key][mode]
            rows = checks(colors)
            failed = [row for row in rows if not row['pass']]
            if failed:
                raise ValueError(f'Contrast gate failed for {key}/{mode}: {failed}')
            audit[key][mode] = rows
    return data['themes'], resolved, audit


def theme_styles(resolved):
    chunks = ['/* Generated by tools/build.py from tokens/themes.json. Edit the inputs. */']
    for key, modes in resolved.items():
        selector = f"[data-theme='{key}']"
        if key == 'tide': selector = ':root, ' + selector
        chunks.append(selector + ' {')
        for mode, colors in modes.items():
            for role, value in colors.items():
                if role == 'texture-opacity':
                    chunks.append(f'  --tide-palette-texture-{mode}: {value};')
                else:
                    chunks.append(f'  --tide-palette-{role}-{mode}: {css(value)};')
        chunks.append('}')
    roles = [role for role in next(iter(resolved.values()))['light'] if role != 'texture-opacity']
    chunks.append(':root, [data-theme] {\n  color-scheme: light dark;')
    for role in roles:
        chunks.append(f'  --tide-color-{role}: light-dark(var(--tide-palette-{role}-light), var(--tide-palette-{role}-dark));')
    chunks.extend([
        '  --tide-texture-opacity: var(--tide-palette-texture-light);',
        '  --tide-border-hairline: var(--tide-border-width) solid var(--tide-color-border-subtle);',
        '  --tide-border-control: var(--tide-border-width) solid var(--tide-color-border-control);',
        '}',
        "[data-mode='light'] { color-scheme: only light; --tide-texture-opacity: var(--tide-palette-texture-light); }",
        "[data-mode='dark'] { color-scheme: only dark; --tide-texture-opacity: var(--tide-palette-texture-dark); }",
        "[data-mode='system'] { color-scheme: light dark; }",
        '@media (prefers-color-scheme: dark) {',
        "  :root:not([data-mode='light']), [data-theme]:not([data-mode='light']):not([data-mode='dark']), [data-mode='system'] { --tide-texture-opacity: var(--tide-palette-texture-dark); }",
        '}',
    ])
    return '\n'.join(chunks) + '\n'
